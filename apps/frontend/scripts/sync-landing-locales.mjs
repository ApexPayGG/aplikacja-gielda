for (const locale of TARGET_LOCALES) {
  const filePath = path.join(LOCALES_DIR, locale, "common.json");
  const data = JSON.parse(fs.readFileSync(filePath, "utf8"));

  if (LANDING[locale]) {
    data.landing = deepMerge(data.landing ?? {}, LANDING[locale]);
  }

  const legal = LEGAL[locale] ?? LEGAL.en;
  data.legal = { ...(data.legal ?? {}), ...legal };

  fs.writeFileSync(filePath, `${JSON.stringify(data, null, 2)}\n`, "utf8");
  console.log(`Updated ${locale}/common.json`);
}
